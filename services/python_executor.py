"""
Python Executor

Robust executor for executing Python code generated by GPT-4.
Handles all data operations: formulas, cleaning, filtering, sorting, etc.
"""

import pandas as pd
import numpy as np
from typing import Dict, List, Optional, Any
from datetime import datetime, date, timedelta
import logging
import re
from services.cleaning.dates import DateCleaner
from services.cleaning.currency import CurrencyCleaner
from services.cleaning.text import TextCleaner

logger = logging.getLogger(__name__)


class PythonExecutor:
    """Robust Python code executor for Excel operations"""
    
    def __init__(self, df: pd.DataFrame):
        """
        Initialize executor with dataframe
        
        Args:
            df: DataFrame to operate on
        """
        self.df = df.copy()  # Work on copy
        self.original_df = df.copy()
        self.result = None
        self.execution_log: List[str] = []
        self.errors: List[str] = []
    
    def execute(self, python_code: str, operation_meta: Optional[Dict] = None) -> Dict[str, Any]:
        """
        Execute Python code safely
        
        Args:
            python_code: Python code string to execute
            operation_meta: Optional metadata about the operation
        
        Returns:
            Dict with execution results
        """
        operation_meta = operation_meta or {}
        description = operation_meta.get("description", "Operation")
        result_type = operation_meta.get("result_type", "dataframe")
        
        # Step 1: Validate code
        validation_result = self._validate_code(python_code, description=description)
        if not validation_result["valid"]:
            error_msg = f"Code validation failed: {validation_result['error']}"
            self.errors.append(error_msg)
            self.execution_log.append(f"✗ {description}: {error_msg}")
            logger.error(f"Code validation failed for: {description}\nOriginal code: {python_code[:500]}")
            raise RuntimeError(error_msg)
        
        # Use cleaned code if available, otherwise use original
        code_to_execute = validation_result.get("cleaned_code", python_code)
        
        # Additional check: Log if code uses 're' module for phone formatting (warning)
        if 'phone' in description.lower() or 'format' in description.lower():
            if 're.sub' in code_to_execute or 're.findall' in code_to_execute or 're.match' in code_to_execute:
                logger.warning(f"⚠️ Generated code uses 're' module for phone formatting - should use TextCleaner.format_phone_numbers() instead:\n{code_to_execute[:800]}")
        
        # Additional check: Warn if mean/sum/median/std might be applied to object columns
        # This is a common error when combining tables - columns become object dtype
        aggregation_patterns = [r'\.mean\(\)', r'\.sum\(\)', r'\.median\(\)', r'\.std\(\)', r'\.agg\([^)]*mean', r'\.agg\([^)]*sum']
        has_aggregation = any(re.search(pattern, code_to_execute) for pattern in aggregation_patterns)
        if has_aggregation and not any(pattern in code_to_execute for pattern in ['select_dtypes', 'is_numeric_dtype', 'dtype']):
            logger.warning(f"⚠️ Code contains aggregation functions but may not check for numeric columns. After combining tables, use df.select_dtypes(include=[np.number]) before aggregation:\n{code_to_execute[:800]}")
        
        # Step 2: Prepare execution environment
        exec_globals = self._build_execution_environment()
        
        # Step 3: Execute code
        try:
            # Execute the cleaned code
            exec(code_to_execute, exec_globals)
            
            # Debug: Log extracted names and contacts if they exist
            if 'names' in exec_globals:
                names_list = exec_globals.get('names', [])
                logger.info(f"🔍 Extracted names count: {len(names_list)}, sample: {names_list[:5] if len(names_list) > 0 else '[]'}")
            if 'contacts' in exec_globals:
                contacts_list = exec_globals.get('contacts', [])
                logger.info(f"🔍 Extracted contacts count: {len(contacts_list)}, sample: {contacts_list[:5] if len(contacts_list) > 0 else '[]'}")
            
            # Step 4: Extract results
            result = self._extract_results(exec_globals, result_type)
            
            # Step 5: Update dataframe and normalize structure
            if 'df' in exec_globals:
                from services.dataframe_normalizer import normalize_dataframe
                self.df = normalize_dataframe(exec_globals['df'])
                
                # Debug: Log DataFrame state after execution
                if 'Student Name' in self.df.columns:
                    filled_student = self.df['Student Name'].notna().sum()
                    logger.info(f"🔍 After execution - Student Name: {filled_student}/{len(self.df)} filled")
                if 'Contact No.' in self.df.columns:
                    filled_contact = self.df['Contact No.'].notna().sum()
                    logger.info(f"🔍 After execution - Contact No.: {filled_contact}/{len(self.df)} filled")
            
            # Step 6: Store result
            if result is not None:
                self.result = result
            
            # Step 7: Log success
            self.execution_log.append(f"✓ {description}")
            logger.info(f"Successfully executed: {description}")
            
            return {
                "success": True,
                "result": result,
                "description": description,
                "rows_affected": len(self.df),
                "columns": list(self.df.columns)
            }
            
        except NameError as e:
            error_str = str(e)
            # Special handling for 're' variable scoping issues
            if "'re'" in error_str or "'re' is not defined" in error_str.lower() or "cannot access local variable 're'" in error_str.lower():
                logger.error(f"❌ 're' scoping error detected in generated code:\n{python_code[:500]}")
                error_msg = f"Variable 're' scoping error: {error_str}. DO NOT use 're' module for phone formatting. Use TextCleaner.format_phone_numbers() instead. Generated code:\n{python_code[:300]}"
            else:
                error_msg = self._handle_name_error(e, python_code)
            self.errors.append(error_msg)
            self.execution_log.append(f"✗ {description}: {error_msg}")
            raise RuntimeError(error_msg)
            
        except KeyError as e:
            error_str = str(e)
            # Check if this is a drop operation trying to drop non-existent columns
            # If so, handle gracefully (columns might have been dropped already or never created)
            if "drop" in python_code.lower() and ("not found in axis" in error_str or "not found" in error_str.lower()):
                # Extract column names from error if possible (re is already imported at module level)
                col_match = re.search(r"\[(.*?)\]", error_str)
                if col_match:
                    missing_cols = col_match.group(1)
                    logger.warning(f"⚠️ Drop operation: Columns {missing_cols} not found, skipping drop (may have been dropped already or never created)")
                    self.execution_log.append(f"⚠ {description}: Columns {missing_cols} not found, skipping (safe to ignore)")
                    # Return success since this is a cleanup operation
                    return {
                        "success": True,
                        "result": None,
                        "description": description,
                        "rows_affected": len(self.df),
                        "columns": list(self.df.columns),
                        "warning": f"Columns {missing_cols} not found, operation skipped"
                    }
            
            error_msg = f"Column not found: {str(e)}. Available columns: {list(self.df.columns)}"
            self.errors.append(error_msg)
            self.execution_log.append(f"✗ {description}: {error_msg}")
            raise RuntimeError(error_msg)
            
        except ValueError as e:
            error_str = str(e)
            # Check for the specific "Length of values does not match length of index" error
            if "Length of values" in error_str and "does not match length of index" in error_str:
                error_msg = f"Execution failed: {error_str}. This usually happens when trying to assign a list of values to a DataFrame row. When adding rows, create a dictionary with ONLY the columns you need, then use pd.concat([df, pd.DataFrame([new_row])], ignore_index=True). Example: new_row = {{'ColumnName': value}}; df = pd.concat([df, pd.DataFrame([new_row])], ignore_index=True)"
            else:
                error_msg = f"Execution failed: {error_str}"
            self.errors.append(error_msg)
            self.execution_log.append(f"✗ {description}: {error_msg}")
            logger.error(f"Execution error: {error_msg}\nCode: {python_code[:200]}")
            raise RuntimeError(error_msg)
            
        except re.error as e:
            error_msg = f"Execution failed: Invalid regex pattern: {str(e)}. When removing or replacing special characters like *, ?, +, (, ), [, ], {{, }}, ^, $, |, \\, use regex=False. Example: df['Column'] = df['Column'].str.replace('*', '', regex=False)"
            self.errors.append(error_msg)
            self.execution_log.append(f"✗ {description}: {error_msg}")
            logger.error(f"Execution error: {error_msg}\nCode: {python_code[:200]}")
            raise RuntimeError(error_msg)
            
        except UnboundLocalError as e:
            error_str = str(e)
            # Special handling for 're' variable scoping errors
            if "cannot access local variable 're'" in error_str.lower() or "local variable 're'" in error_str.lower():
                logger.error(f"❌ 're' scoping error in generated code:\n{python_code[:1000]}")
                error_msg = f"Execution failed: Variable 're' scoping error. DO NOT use 're' module for phone formatting. Use TextCleaner.format_phone_numbers() instead. Error: {error_str}\nGenerated code:\n{python_code[:500]}"
                self.errors.append(error_msg)
                self.execution_log.append(f"✗ {description}: {error_msg}")
                logger.error(f"Execution error: {error_msg}")
                raise RuntimeError(error_msg)
            else:
                error_msg = f"Execution failed: {error_str}"
                self.errors.append(error_msg)
                self.execution_log.append(f"✗ {description}: {error_msg}")
                logger.error(f"Execution error: {error_msg}\nCode: {python_code[:200]}")
                raise RuntimeError(error_msg)
            
        except Exception as e:
            error_str = str(e)
            # Check for 're' scoping errors in general Exception catch
            if "cannot access local variable 're'" in error_str.lower() or "local variable 're'" in error_str.lower():
                logger.error(f"❌ 're' scoping error in generated code:\n{python_code[:1000]}")
                error_msg = f"Execution failed: Variable 're' scoping error. DO NOT use 're' module for phone formatting. Use TextCleaner.format_phone_numbers() instead. Error: {error_str}\nGenerated code:\n{python_code[:500]}"
            # Check for aggregation function errors on object dtype columns
            elif "agg function failed" in error_str.lower() or ("dtype->object" in error_str.lower() and ("mean" in error_str.lower() or "sum" in error_str.lower() or "median" in error_str.lower())):
                logger.error(f"❌ Aggregation error on object dtype column:\n{python_code[:1000]}")
                error_msg = f"Execution failed: Cannot apply aggregation function (mean/sum/median) to object dtype columns. After combining tables, columns may become object dtype. Use df.select_dtypes(include=[np.number]) to select only numeric columns before aggregation. Example: numeric_cols = df.select_dtypes(include=[np.number]).columns; df.groupby(...)[numeric_cols].mean(). Error: {error_str}\nGenerated code:\n{python_code[:500]}"
            else:
                error_msg = f"Execution failed: {error_str}"
            self.errors.append(error_msg)
            self.execution_log.append(f"✗ {description}: {error_msg}")
            logger.error(f"Execution error: {error_msg}\nCode: {python_code[:500]}")
            raise RuntimeError(error_msg)
    
