    def _clean_code(self, python_code: str) -> str:
        """
        Clean code - simplified to only essential fixes
        
        Args:
            python_code: Raw code string that might contain markdown
            
        Returns:
            Cleaned code string
        """
        code = python_code.strip()
        
        # 1. Replace literal \n escape sequences with actual newlines
        code = code.replace('\\n', '\n')
        
        # 2. Remove markdown code blocks
        if code.startswith('```'):
            lines = code.split('\n')
            if lines[0].startswith('```'):
                lines = lines[1:]
            if lines and lines[-1].strip() == '```':
                lines = lines[:-1]
            code = '\n'.join(lines)
        
        # Remove any remaining ``` markers
        code = re.sub(r'```[a-z]*\n?', '', code)
        
        # 2.5. Fix str.extract() patterns missing capture groups (CRITICAL FIX)
        # Pattern: .str.extract(r'PATTERN') -> .str.extract(r'(PATTERN)')
        # This is a common LLM error that causes "pattern contains no capture groups"
        # Match .str.extract(r'...') or .str.extract(r"...") patterns without capture groups
        extract_pattern = re.compile(
            r'\.str\.extract\s*\(\s*(r[\'"])([^\'"]+?)([\'"])',
            re.IGNORECASE
        )
        
        def fix_extract_match(match):
            quote_start = match.group(1)  # r' or r"
            pattern_content = match.group(2)  # The pattern content
            quote_end = match.group(3)  # ' or "
            
            # Check if pattern already has balanced capture groups
            # Simple check: if it has ( and ) and they're balanced, assume it's fine
            if '(' in pattern_content and ')' in pattern_content:
                # Check if parentheses are balanced (simple check)
                open_count = pattern_content.count('(')
                close_count = pattern_content.count(')')
                if open_count == close_count and open_count > 0:
                    return match.group(0)  # Already has capture groups, don't modify
            
            # Wrap pattern in capture group
            fixed = f".str.extract({quote_start}({pattern_content}){quote_end}"
            logger.warning(f"🔧 Fixed str.extract() pattern missing capture group: {match.group(0)[:80]} → {fixed[:80]}")
            return fixed
        
        # Replace all matches
        code = extract_pattern.sub(fix_extract_match, code)
        
        # 3. Fix for/if statements on same line with semicolons (CRITICAL - Python syntax requirement)
        # Also handle cases where semicolon is followed by assignment then control flow: "; var = 0 for i"
        if ';' in code:
            # First, split on semicolons
            segments = code.split(';')
            parts = []
            
            for segment in segments:
                segment = segment.strip()
                if not segment:
                    continue
                
                # Check if segment contains concatenated control flow (e.g., "col_a_idx = 0 for i")
                # This handles: "; col_a_idx = 0 for i in range"
                if re.search(r'\s+(for|if|while|elif|else)\s+', segment):
                    # Split the segment further - find where control flow starts
                    # Pattern: "var = value for" -> "var = value\nfor"
                    segment = re.sub(r'(\w+\s*=\s*[^\s]+?)\s+(for|if|while|elif|else)\s+', r'\1\n\2 ', segment)
                    # Also handle: "condition: if" -> "condition:\nif"
                    segment = re.sub(r'([^:]):\s+(if|for|while|elif|else)\s+', r'\1:\n\2 ', segment)
                
                parts.append(segment)
            
            code = '\n'.join(parts)
        
        # 4. Fix method chains split across lines (common LLM error)
        # Pattern: method()\n['key'] or method()\n.method2()
        # Also handles: df[...]\n['key'] or df[...]\n.tolist()
        # Join them back to single line
        lines = code.split('\n')
        fixed_lines = []
        i = 0
        while i < len(lines):
            line = lines[i].strip()
            # Check if next line starts with [ or . (method chain continuation)
            if i + 1 < len(lines):
                next_line = lines[i + 1].strip()
                # Also check if current line ends with ] and next starts with [ or .
                if (next_line.startswith('[') or next_line.startswith('.')) and not next_line.startswith('[') == False:
                    # Join them together
                    line = line + next_line
                    i += 1  # Skip next line since we merged it
                    # Continue checking if there are more continuations
                    while i < len(lines):
                        next_line = lines[i].strip()
                        if next_line.startswith('[') or next_line.startswith('.'):
                            line = line + next_line
                            i += 1
                        else:
                            break
            fixed_lines.append(line)
            i += 1
        code = '\n'.join(fixed_lines)
        
        # 4.1. Fix method chains that are split with spaces/newlines in the middle
        # Pattern: df[...]\n['key'] or df[...] ['key'] (space before bracket)
        # This handles cases like: df[df['Dept'] == 'Sales']\n['Employee'].tolist()
        code = re.sub(r'\]\s*\n\s*\[', '][', code)  # ]\n[ -> ][
        code = re.sub(r'\]\s+\[', '][', code)  # ] [ -> ][
        
        # 4.5. CRITICAL: UNIVERSAL FIX for missing line breaks before control flow
        # This handles ALL cases where control flow keywords appear without proper line breaks
        # Pattern: ANYTHING followed by control flow keyword (if, elif, else, for, while)
        # Examples:
        #   "def func(): if" -> "def func():\n    if"
        #   "return 'Low' elif" -> "return 'Low'\nelif"
        #   "col_a_idx = 0 for" -> "col_a_idx = 0\nfor"
        #   ") if" -> ")\nif"
        #   "statement: if" -> "statement:\nif"
        
        # UNIVERSAL PATTERN: Insert newline before control flow keywords
        # Match: word boundary, then control flow keyword, but NOT if it's already at start of line
        # This pattern catches ALL cases where control flow appears mid-line
        
        # Step 1: Fix control flow that appears after statements (not at start of line)
        # Pattern: Any non-whitespace, non-colon character followed by control flow
        # But exclude cases where it's part of a valid expression like "if x in y"
        control_flow_keywords = r'(if|elif|else|for|while)'
        
        # Pattern: End of statement (word, number, ), ], }, ', ") followed by control flow
        # This catches: "statement if", "value for", ") if", "] elif", etc.
        code = re.sub(
            r'([a-zA-Z0-9_\)\]\}\'"])\s+' + control_flow_keywords + r'\s+',
            r'\1\n\2 ',
            code
        )
        
        # Step 2: Fix control flow that appears after colons (except in if/for/while statements)
        # Pattern: "statement: if" -> "statement:\nif" (but not "if x: if y" which is valid)
        code = re.sub(
            r'([^:\n]):\s+' + control_flow_keywords + r'\s+(?!\w+\s+in\s+)',
            r'\1:\n\2 ',
            code
        )
        
        # Step 3: Fix control flow that appears after closing parentheses/brackets
        # Pattern: ") if", "] for", etc.
        code = re.sub(
            r'(\)|\])\s+' + control_flow_keywords + r'\s+',
            r'\1\n\2 ',
            code
        )
        
        # Step 4: Fix control flow that appears after return/break/continue/pass
        # Pattern: "return 'Low' elif" -> "return 'Low'\nelif"
        code = re.sub(
            r'(return|break|continue|pass)\s+([^\n]+?)\s+' + control_flow_keywords + r'\s+',
            r'\1 \2\n\3 ',
            code
        )
        
        # Step 5: Fix control flow that appears after variable assignments
        # Pattern: "var = value for" -> "var = value\nfor"
        code = re.sub(
            r'(\w+\s*=\s*[^\n=]+?)\s+' + control_flow_keywords + r'\s+',
            r'\1\n\2 ',
            code
        )
        
        # Additional fix: Any statement ending with identifier/number followed by control flow
        # Pattern: identifier for|number for|identifier if|number if
        # This catches cases like: col_a_idx = 0 for (already handled above) or other edge cases
        # But be careful not to match things like "for x in range(10)" which is valid
        # Only match if it's clearly a statement followed by control flow (not part of the control flow itself)
        pattern3 = r'(\b\w+\b|\d+)\s+(for|if|while|elif|else)\s+(?!\w+\s+in\s+|\w+\s*\(|\w+\s*:)'
        # Actually, this is too risky - might break valid code. Let's skip this and rely on the assignment pattern above.
        
        # Fix indentation issues: ensure proper indentation for control flow blocks
        lines = code.split('\n')
        fixed_lines = []
        indent_level = 0
        for i, line in enumerate(lines):
            stripped = line.strip()
            if not stripped:  # Empty line
                fixed_lines.append('')
                continue
            
            # Check if this is a control flow statement
            if re.match(r'^(for|if|while|elif|else)\s+', stripped):
                # Control flow statement - should be at base indent (0)
                fixed_lines.append(stripped)
                indent_level = 1  # Next line should be indented
            elif re.match(r'^elif\s+|^else\s*:', stripped):
                # elif/else - should be at base indent (0)
                indent_level = 0
                fixed_lines.append(stripped)
                indent_level = 1  # Next line should be indented
            elif indent_level > 0 and not stripped.startswith('    '):
                # This should be indented but isn't - add indentation
                fixed_lines.append('    ' * indent_level + stripped)
            else:
                # Check if line ends with ':' - next line should be indented
                if stripped.endswith(':'):
                    fixed_lines.append(line)
                    indent_level = 1
                else:
                    fixed_lines.append(line)
                    # If this line doesn't continue a block, reset indent
                    if not stripped.endswith('\\'):
                        indent_level = 0
        
        code = '\n'.join(fixed_lines)
        
        # Final pass: fix any remaining indentation issues
        # If a line starts with 'if', 'for', 'while' and previous line doesn't end with ':', ensure it's on new line
        lines = code.split('\n')
        final_lines = []
        for i, line in enumerate(lines):
            stripped = line.strip()
            if i > 0 and re.match(r'^(for|if|while|elif|else)\s+', stripped):
                prev_line = final_lines[-1] if final_lines else ''
                if prev_line and not prev_line.rstrip().endswith(':') and prev_line.strip():
                    # Ensure proper separation
                    pass
            final_lines.append(line)
        code = '\n'.join(final_lines)
        
        # 5. Fix common syntax errors
        code = re.sub(r'\[None\)\*\(', '[None] * (', code)  # [None)*( -> [None] * (
        code = re.sub(r'\bgrouped\.co\b', 'grouped.columns', code)  # grouped.co -> grouped.columns
        code = re.sub(r'\bfor_in\b', 'for _ in', code)  # for_in -> for _ in
        code = re.sub(r'\bfor\s+_in\b', 'for _ in', code)  # for _in -> for _ in
        
        # 6. Final pass: Fix any remaining concatenated control flow statements
        # Handle cases like: "statement if condition:" -> "statement\nif condition:"
        # But be careful not to break valid code like "if x in y:"
        code = re.sub(r'([^:\n])\s+(for|if|while|elif|else)\s+([^i][^n]|i[^n]|in[^\s])', r'\1\n\2 \3', code)
        
        # 7. Fix indentation: Properly track nested indentation levels
        # CRITICAL: Preserve existing indentation when correct, only fix when wrong
        # This is a simpler, more reliable approach that preserves correct indentation
        lines = code.split('\n')
        fixed_lines = []
        indent_stack = []  # Stack to track indentation levels
        
        for i, line in enumerate(lines):
            stripped = line.strip()
            if not stripped:
                fixed_lines.append('')
                continue
            
            # Calculate existing indentation
            existing_indent = len(line) - len(line.lstrip())
            existing_indent_level = existing_indent // 4
            
            # Check if previous line ended with ':' - next line should be indented
            if i > 0 and fixed_lines:
                prev_line_stripped = fixed_lines[-1].strip()
                if prev_line_stripped.endswith(':'):
                    # Previous line was control flow/function - this line MUST be indented
                    # Calculate required indent from the previous line's indent
                    prev_line = fixed_lines[-1]
                    prev_indent = len(prev_line) - len(prev_line.lstrip())
                    required_indent = prev_indent + 4
                    
                    if existing_indent < required_indent:
                        # Not indented enough - fix it
                        fixed_lines.append(' ' * required_indent + stripped)
                        continue
                    # If already properly indented, fall through to preserve it
            
            # Check if this is elif/else - should be at same level as matching if/for
            if re.match(r'^elif\s+|^else\s*:', stripped):
                # Find the matching if/for by looking back
                # elif/else should be at the same indent as the matching if/for
                matching_indent = 0
                for j in range(len(fixed_lines) - 1, -1, -1):
                    prev_stripped = fixed_lines[j].strip()
                    if re.match(r'^(if|for|while)\s+', prev_stripped):
                        # Found matching if/for - get its indent
                        prev_line = fixed_lines[j]
                        matching_indent = len(prev_line) - len(prev_line.lstrip())
                        break
                
                # CRITICAL: elif/else MUST be at the same indent as the matching if/for
                # Don't use existing indent if it's wrong - always use matching indent
                fixed_lines.append(' ' * matching_indent + stripped)
                continue
            
            # For all other lines, preserve existing indentation if it looks reasonable
            # Only fix if it's clearly wrong (e.g., control flow at wrong level)
            if re.match(r'^(for|if|while)\s+', stripped):
                # Control flow statement
                # If it's at base level (0) or reasonably indented, preserve it
                if existing_indent_level == 0 or (existing_indent_level > 0 and existing_indent % 4 == 0):
                    fixed_lines.append(line)
                else:
                    # Fix to nearest 4-space boundary
                    fixed_indent = (existing_indent_level * 4)
                    fixed_lines.append(' ' * fixed_indent + stripped)
            else:
                # Regular line - preserve existing indentation
                fixed_lines.append(line)
        
        code = '\n'.join(fixed_lines)
        
        return code.strip()
    
    def _validate_code(self, python_code: str, description: str = "") -> Dict[str, Any]:
        """
        Validate code before execution - simplified
        
        Returns:
            {"valid": bool, "error": str, "cleaned_code": str}
        """
        # Clean the code first
        cleaned_code = self._clean_code(python_code)
        
        # Log the cleaned code for debugging
        logger.info(f"🔍 Original code (first 500 chars): {python_code[:500]}")
        logger.info(f"🔍 Cleaned code (first 500 chars): {cleaned_code[:500]}")
        logger.info(f"🔍 Full cleaned code:\n{cleaned_code}")
        
        # Check if code is empty
        if not cleaned_code or not cleaned_code.strip():
            return {"valid": False, "error": "Code is empty after cleaning"}
        
        # Check 1: No import statements
        if re.search(r'\bimport\s+\w+|from\s+\w+\s+import', cleaned_code):
            return {"valid": False, "error": "Import statements are not allowed"}
        
        # Check 2: Prevent problematic use of 're' module that causes scoping errors
        # Only block if there's an assignment to 're' (which causes UnboundLocalError)
        # Allow legitimate use of 're' module (it's in the execution context)
        lines = cleaned_code.split('\n')
        problematic_lines = []
        
        for i, line in enumerate(lines, 1):
            line_stripped = line.strip()
            
            # CRITICAL: Only block assignments to 're' variable (this causes UnboundLocalError)
            # Allow using 're' module (re.sub, re.findall, etc.) - it's available in execution context
            # But if code assigns to 're', Python treats it as local, causing scoping issues
            
            # Check for direct assignment: re = ... (this causes UnboundLocalError)
            # Use word boundary to match 're' as a standalone word, not part of 'result', 'return', etc.
            # Pattern: \b matches word boundary, ensuring 're' is not part of another word
            if re.search(r'\bre\s*=', line_stripped):
                # This is an assignment to 're' variable - problematic!
                # The \b word boundary ensures it won't match 'result =', 'return =', etc.
                problematic_lines.append(f"Line {i}: {line_stripped} (assigns to 're' variable - causes scoping errors. Use 'result', 'regex_result', or another variable name instead.)")
            
            # Also check for patterns like: for re in ... (loop variable) or re, = ... (tuple unpacking)
            if re.search(r'\bfor\s+re\s+in\b', line_stripped):
                problematic_lines.append(f"Line {i}: {line_stripped} (uses 're' as loop variable - causes scoping errors)")
            if re.search(r'\bre\s*,\s*\w+\s*=\s*', line_stripped):
                problematic_lines.append(f"Line {i}: {line_stripped} (unpacks to 're' variable - causes scoping errors)")
        
        if problematic_lines:
            logger.error(f"❌ Code assigns to 're' variable which causes scoping errors:\n" + "\n".join(problematic_lines[:5]))
            return {
                "valid": False, 
                "error": f"Code cannot assign to 're' variable (causes scoping errors). For text splitting, use pandas str.split() method (e.g., df['Col'].astype(str).str.split(' ', expand=True)). For phone formatting, use TextCleaner.format_phone_numbers(). For regex operations, use 'result' or 'regex_result' as variable name instead of 're'. Problematic lines:\n" + "\n".join(problematic_lines[:3])
            }
        
        # Check 3: No dangerous operations
        dangerous_patterns = [
            r'\bopen\s*\(', r'\bread\s*\(', r'\bwrite\s*\(',
            r'__file__', r'__import__', r'eval\s*\(', r'exec\s*\(',
            r'\bos\.|sys\.|subprocess\.|shutil\.',
        ]
        for pattern in dangerous_patterns:
            if re.search(pattern, cleaned_code):
                return {"valid": False, "error": f"Dangerous operation detected: {pattern}"}
        
        # Check 4: Basic syntax validation
        try:
            compile(cleaned_code, '<string>', 'exec')
        except SyntaxError as e:
            error_line = getattr(e, 'lineno', 'unknown')
            code_preview = cleaned_code[:300] if len(cleaned_code) > 300 else cleaned_code
            return {
                "valid": False, 
                "error": f"Syntax error at line {error_line}: {str(e)}\nCode preview:\n{code_preview}",
                "cleaned_code": cleaned_code
            }
        
        return {"valid": True, "error": None, "cleaned_code": cleaned_code}
    
    def _extract_results(self, exec_globals: Dict, result_type: str) -> Any:
        """Extract results from execution environment"""
        if result_type == "single_value":
            # Single value result (SUM, AVERAGE, etc.)
            if 'result' in exec_globals and exec_globals['result'] is not None:
                return exec_globals['result']
            return None
        
        elif result_type == "dataframe":
            # DataFrame operation (filter, sort, etc.)
            if 'df' in exec_globals:
                return exec_globals['df']
            return self.df
        
        elif result_type == "new_column":
            # New column created
            if 'df' in exec_globals:
                return exec_globals['df']
            return self.df
        
        return None
    
